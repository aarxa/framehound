"""Generate commands.inc for the framehound Vulkan layer from the Vulkan registry (vk.xml).

Every vkCmd* command the installed headers declare gets an entry in the layer's command table and, unless the layer
handles it by hand (draws, pipeline binds and a few more), a wrapper that records the call into the app's command
buffer and into each of its shadow copies. A command the layer didn't wrap would be missing from the shadows, so they
are all generated rather than written out.

    python3 native/layer/gen_commands.py /opt/homebrew/share/vulkan/registry/vk.xml native/layer/commands.inc
"""
import sys
import xml.etree.ElementTree as ET

# written by hand in layer.cpp
HANDLED = {
    "vkCmdBindPipeline", "vkCmdDraw", "vkCmdDrawIndexed", "vkCmdExecuteCommands", "vkCmdBindDescriptorSets",
    "vkCmdDrawIndirect", "vkCmdDrawIndexedIndirect",
    "vkCmdDrawIndirectCount", "vkCmdDrawIndirectCountKHR", "vkCmdDrawIndirectCountAMD",
    "vkCmdDrawIndexedIndirectCount", "vkCmdDrawIndexedIndirectCountKHR", "vkCmdDrawIndexedIndirectCountAMD",
}

# generated, but also reported to a Note<Command>(Recording*, args) function in layer.cpp, which keeps track of the
# buffers a draw reads: the mesh it draws
NOTED = {
    "vkCmdBindIndexBuffer", "vkCmdBindIndexBuffer2", "vkCmdBindIndexBuffer2KHR",
    "vkCmdBindVertexBuffers", "vkCmdBindVertexBuffers2", "vkCmdBindVertexBuffers2EXT",
}


def apis(el, attr="api"):
    v = el.get(attr)
    return v.split(",") if v else ["vulkan"]


def main(registry, out):
    reg = ET.parse(registry).getroot()

    # commands the installed vulkan_core.h declares: core versions and non-platform, non-provisional extensions
    available = set()
    for feature in reg.findall("feature"):
        if "vulkan" not in apis(feature):
            continue
        for req in feature.findall("require"):
            available.update(c.get("name") for c in req.findall("command"))
    for ext in reg.find("extensions").findall("extension"):
        if "vulkan" not in ext.get("supported", "").split(","):
            continue
        if ext.get("platform") or ext.get("provisional") == "true":
            continue
        for req in ext.findall("require"):
            if "vulkan" not in apis(req):
                continue
            available.update(c.get("name") for c in req.findall("command"))

    sigs, aliases = {}, {}
    for c in reg.find("commands").findall("command"):
        if "vulkan" not in apis(c):
            continue
        if c.get("alias"):
            aliases[c.get("name")] = c.get("alias")
            continue
        name = c.find("proto/name").text
        params = [p for p in c.findall("param") if "vulkan" in apis(p)]
        decls = [" ".join("".join(p.itertext()).split()) for p in params]
        names = [p.find("name").text for p in params]
        sigs[name] = (c.find("proto/type").text, decls, names)
    for name, target in aliases.items():
        if target in sigs:
            sigs[name] = sigs[target]

    cmds = sorted(n for n in sigs if n.startswith("vkCmd") and n in available
                  and sigs[n][1] and sigs[n][1][0].startswith("VkCommandBuffer"))
    lines = ["// Generated by gen_commands.py from vk.xml; do not edit.",
             "// Included twice by layer.cpp: once for the command table, once (after Device) for the wrappers.", ""]
    lines.append("#ifdef FH_COMMAND_TABLE")
    lines.append("struct CmdTable {")
    lines += [f"  PFN_{n} {n[2:]} = nullptr;" for n in cmds]
    lines.append("};")
    lines.append("")
    lines.append("static void LoadCmdTable(CmdTable& t, PFN_vkGetDeviceProcAddr gdpa, VkDevice device) {")
    lines += [f'  t.{n[2:]} = (PFN_{n})gdpa(device, "{n}");' for n in cmds]
    lines.append("}")
    lines.append("#endif")
    lines.append("")
    lines.append("#ifdef FH_COMMAND_WRAPPERS")
    for n in cmds:
        if n in HANDLED:
            continue
        ret, decls, names = sigs[n]
        if ret != "void":
            continue  # recording commands return nothing
        rest = ", ".join(names[1:])
        call_rest = f", {rest}" if rest else ""
        lines.append(f"static VKAPI_ATTR void VKAPI_CALL fh_{n[2:]}({', '.join(decls)}) {{")
        lines.append(f"  Recording* r = RecordingOf({names[0]});")
        lines.append(f"  r->device->cmd.{n[2:]}({names[0]}{call_rest});")
        lines.append(f"  for (VkCommandBuffer s : r->shadows) r->device->cmd.{n[2:]}(s{call_rest});")
        if n in NOTED:
            lines.append(f"  Note{n[2:]}(r{call_rest});")
        lines.append("}")
    lines.append("")
    lines.append("static PFN_vkVoidFunction GeneratedCommand(const char* name) {")
    for n in cmds:
        if n in HANDLED or sigs[n][0] != "void":
            continue
        lines.append(f'  if (!strcmp(name, "{n}")) return (PFN_vkVoidFunction)fh_{n[2:]};')
    lines.append("  return nullptr;")
    lines.append("}")
    lines.append("#endif")
    open(out, "w").write("\n".join(lines) + "\n")
    print(f"{len(cmds)} commands, {len(cmds) - len(HANDLED)} generated wrappers -> {out}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
